const { _electron: electron, expect } = require('@playwright/test');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
(async () => {
  const root = path.resolve(__dirname, '..', '..');
  const directory = fs.mkdtempSync(path.join(root, 'artifacts', 'desktop-smoke-'));
  execFileSync(path.join(root, '.venv', 'Scripts', 'python.exe'), ['-X', 'utf8', path.join(root, 'tests', 'desktop_fixture.py'), directory], { cwd: root });
  const app = await electron.launch({ args: [path.join(root, 'desktop')],
    env: { ...process.env, AGENT_API_KEY: '', AGENT_DATA_DIR: directory, AGENT_PROFILE_DIR: path.join(directory, 'profile'), AGENT_TEST_MODE: '1' }, timeout: 40000 });
  try {
    const page = await app.firstWindow();
    await page.waitForLoadState('networkidle');
    assert.equal(await page.title(), 'Archive Zero · 零号档案');
    assert.equal(await page.locator('.rail-brand strong').textContent(), 'Archive Zero');
    const identity = await app.evaluate(({ app }) => ({ name: app.getName(), profile: app.getPath('userData') }));
    assert.equal(identity.name, 'Archive Zero');
    assert.equal(identity.profile, path.join(directory, 'profile'));
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('button', { name: '模型设置', exact: true }).click();
    await page.getByRole('button', { name: '添加模型', exact: true }).click();
    await page.getByLabel('模型名称', { exact: true }).fill('desktop-model-a');
    await page.getByLabel('模型接口地址', { exact: true }).fill('https://model.example/v1');
    await page.getByLabel('模型API密钥', { exact: true }).fill('desktop-isolated-test-key');
    await page.getByText('接口能力与预算', { exact: true }).click();
    await page.getByLabel('模型上下文窗口', { exact: true }).fill('1000000');
    await page.getByLabel('讨论', { exact: true }).selectOption('model_1');
    await page.getByRole('button', { name: '保存模型设置', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '已保存，新任务使用新设置' }).waitFor();
    assert.equal(await page.getByLabel('模型API密钥', { exact: true }).inputValue(), '');
    await page.getByRole('button', { name: '添加模型', exact: true }).click();
    await page.getByLabel('模型名称', { exact: true }).fill('desktop-model-b');
    await page.getByLabel('模型接口地址', { exact: true }).fill('https://other-model.example/v1');
    await page.getByLabel('模型API密钥', { exact: true }).fill('desktop-second-isolated-key');
    await page.getByLabel('记忆提取', { exact: true }).selectOption('model_2');
    await page.getByRole('button', { name: '保存模型设置', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '已保存，新任务使用新设置' }).waitFor();
    const modelText = fs.readFileSync(path.join(directory, 'models.json'), 'utf8');
    const modelConfig = JSON.parse(modelText);
    assert.deepEqual(modelConfig.stages, { discuss: 'model_1', extract: 'model_2' });
    assert.equal(modelConfig.profiles.model_1.context_window_tokens, 1000000);
    assert.ok(!modelText.includes('desktop-isolated-test-key') && !modelText.includes('desktop-second-isolated-key'));
    await page.getByRole('button', { name: '关闭设置', exact: true }).click();
    await page.getByTitle('添加主题').click();
    await page.getByLabel('名称', { exact: true }).fill('桌面验证主题');
    await page.getByLabel('描述', { exact: true }).fill('验证真实桌面操作，不调用模型。');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await page.locator('.modal').waitFor({ state: 'hidden' });
    await page.getByRole('heading', { name: '桌面验证主题', exact: true }).waitFor();
    await page.getByRole('button', { name: '＋标签', exact: true }).click();
    await page.getByLabel('名称', { exact: true }).fill('工具');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await page.locator('.modal').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('button', { name: '关于我的记忆', exact: true }).click();
    await page.getByRole('button', { name: '添加明确背景或偏好' }).click();
    await page.getByLabel('明确背景或偏好').fill('我熟悉Java，正在学习Python。');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await page.locator('.modal').waitFor({ state: 'hidden' });
    await page.getByText('我熟悉Java，正在学习Python。', { exact: true }).waitFor();
    await page.getByRole('button', { name: '更正', exact: true }).click();
    await page.getByLabel('明确背景或偏好').fill('我熟悉Java，正在系统学习Python。');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await page.locator('.modal').waitFor({ state: 'hidden' });
    await page.getByText('我熟悉Java，正在系统学习Python。', { exact: true }).waitFor();
    await page.getByRole('button', { name: '关闭设置', exact: true }).click();
    await page.getByRole('button', { name: /Agent 工程/ }).click();
    await page.locator('.material-row').first().click();
    await page.getByRole('button', { name: '标为已读', exact: true }).click();
    await page.getByRole('button', { name: '标为未读', exact: true }).waitFor();
    const reply = page.locator('.message.assistant').first();
    await reply.waitFor();
    assert.match(await reply.locator('.run-stats summary').textContent(), /缓存命中率 80.0%/);
    await reply.getByLabel('运行详情', { exact: true }).click();
    await reply.getByRole('table').waitFor();
    assert.equal(await reply.locator('tbody tr').count(), 2);
    await reply.getByLabel('运行详情', { exact: true }).click();
    await page.getByLabel('上下文窗口详情', { exact: true }).click();
    const contextPanel = page.locator('.context-popover');
    await contextPanel.waitFor();
    assert.match(await contextPanel.textContent(), /1,200/);
    assert.equal(await contextPanel.getByRole('progressbar', { name: '最近请求输入占模型窗口', exact: true }).getAttribute('max'), '1000000');
    assert.match(await contextPanel.textContent(), /字节，不是精确 token 拆分/);
    assert.equal(await page.getByLabel('上下文窗口详情', { exact: true }).getAttribute('aria-expanded'), 'true');
    const image = await page.screenshot();
    fs.writeFileSync(path.join(root, 'artifacts', 'desktop-smoke.png'), image);
    const lifecycle = await app.evaluate(({ BrowserWindow }) => {
      const window = BrowserWindow.getAllWindows()[0]; window.show(); window.close();
      return { exists: !window.isDestroyed(), visible: window.isVisible() };
    });
    assert.deepEqual(lifecycle, { exists: true, visible: false });
    await app.evaluate(({BrowserWindow}, file) => {
      const window = BrowserWindow.getAllWindows()[0];
      process.mainModule.require(file).restoreWindow(window);
    }, path.join(root, 'desktop/electron/lifecycle.cjs'));
    assert.equal(await app.evaluate(({BrowserWindow}) => BrowserWindow.getAllWindows()[0].isVisible()), true);
    await app.evaluate(({BrowserWindow}) => BrowserWindow.getAllWindows()[0].minimize());
    await expect.poll(() => app.evaluate(({BrowserWindow}) => BrowserWindow.getAllWindows()[0].isMinimized())).toBe(true);
    await app.evaluate(({BrowserWindow}, file) => process.mainModule.require(file).restoreWindow(BrowserWindow.getAllWindows()[0]), path.join(root, 'desktop/electron/lifecycle.cjs'));
    await expect.poll(() => app.evaluate(({BrowserWindow}) => BrowserWindow.getAllWindows()[0].isMinimized())).toBe(false);
    assert.deepEqual(errors, []);
    console.log('Desktop model settings, CRUD, memory, close-to-tray and screenshot: passed.');
  } finally { await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
