const { _electron: electron, expect } = require('@playwright/test');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');

(async () => {
  const root = path.resolve(__dirname, '..', '..');
  const directory = fs.mkdtempSync(path.join(root, 'artifacts', 'workspace-desktop-'));
  execFileSync(path.join(root, '.venv', 'Scripts', 'python.exe'), ['-X', 'utf8', path.join(root, 'tests', 'desktop_fixture.py'), directory], { cwd: root });
  const app = await electron.launch({ args: [path.join(root, 'desktop')], env: { ...process.env, AGENT_API_KEY: '', AGENT_DATA_DIR: directory, AGENT_TEST_MODE: '1' }, timeout: 40000 });
  let page;
  try {
    page = await app.firstWindow(); await page.waitForLoadState('networkidle');
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.getByTitle('添加主题', { exact: true }).click();
    await page.getByLabel('名称', { exact: true }).fill('论文与研究');
    await page.getByLabel('描述', { exact: true }).fill('理解研究问题、证据与适用边界。');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await page.getByRole('heading', { name: '论文与研究', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Agent 工程', exact: true }).click();
    await page.locator('.discussion-link').first().click();
    await page.locator('.message.assistant').first().waitFor();
    const originalBranch = await page.getByLabel('讨论分支', { exact: true }).inputValue();
    await page.getByLabel('讨论问题', { exact: true }).fill('尚未发送的问题，切换设置后继续。');
    await page.getByRole('button', { name: '切换材料列表', exact: true }).click();
    await expect(page.locator('.material-panel')).toHaveCount(0);
    await page.getByRole('button', { name: '关闭提示', exact: true }).click().catch(() => {});
    fs.writeFileSync(path.join(root, 'artifacts', 'workspace-desktop.png'), await page.screenshot());
    await page.evaluate(async () => { await window.reader.request('/api/settings/models', 'PUT', { version: 1, default: 'reading', profiles: { reading: { model: 'workspace-test-model', base_url: 'https://model.example/v1', api_key: 'isolated-workspace-test-key', strict_tools: false } }, stages: {} }); });
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByLabel('模型名称', { exact: true }).waitFor();
    await page.getByRole('button', { name: '保存模型设置', exact: true }).focus();
    await page.keyboard.press('Tab');
    await expect(page.getByRole('button', { name: '模型设置', exact: true })).toBeFocused();
    await page.locator('.settings-content').evaluate(element => { element.scrollTop = 0; });
    fs.writeFileSync(path.join(root, 'artifacts', 'workspace-model-settings.png'), await page.screenshot());
    await page.getByRole('button', { name: '阅读来源', exact: true }).click();
    await page.getByRole('button', { name: '添加 RSS 来源', exact: true }).click();
    await page.getByLabel('名称', { exact: true }).fill('工程阅读周刊');
    await page.getByLabel('RSS 地址', { exact: true }).fill('https://fixture.test/workspace-feed');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await expect(page.locator('.modal')).toHaveCount(0);
    const source = page.locator('.source').filter({ has: page.getByRole('heading', { name: '工程阅读周刊', exact: true }) });
    await source.waitFor();
    await expect(source.getByLabel('Agent 工程', { exact: true })).toBeChecked();
    await source.getByRole('button', { name: '停用', exact: true }).click();
    await source.getByRole('button', { name: '启用', exact: true }).waitFor();
    fs.writeFileSync(path.join(root, 'artifacts', 'workspace-source-settings.png'), await page.screenshot());
    await page.getByRole('button', { name: '资料库', exact: true }).click();
    await page.getByLabel('导入主题', { exact: true }).selectOption({ label: '论文与研究' });
    await page.getByRole('button', { name: '关于我的记忆', exact: true }).click();
    await page.getByRole('button', { name: '添加明确背景或偏好', exact: true }).click();
    await page.getByLabel('明确背景或偏好', { exact: true }).fill('我偏好结合原文讨论工程问题。');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await page.getByText('我偏好结合原文讨论工程问题。', { exact: true }).waitFor();
    await page.getByLabel('记忆查看范围', { exact: true }).selectOption({ label: '论文与研究 + 全局' });
    await expect(page.getByText('我偏好结合原文讨论工程问题。', { exact: true })).toHaveCount(0);
    await page.keyboard.press('Escape');
    await expect(page.getByRole('dialog', { name: '设置', exact: true })).toHaveCount(0);
    assert.equal(await page.getByLabel('讨论分支', { exact: true }).inputValue(), originalBranch);
    await expect(page.getByLabel('讨论问题', { exact: true })).toHaveValue('尚未发送的问题，切换设置后继续。');
    await page.getByRole('tab', { name: '阅读', exact: true }).click();
    await page.getByRole('heading', { name: '摘要', exact: true }).waitFor();
    await page.getByRole('tab', { name: '讨论', exact: true }).click();
    await expect(page.getByLabel('讨论问题', { exact: true })).toHaveValue('尚未发送的问题，切换设置后继续。');
    await page.getByRole('button', { name: '收起侧边栏', exact: true }).click();
    await page.setViewportSize({ width: 980, height: 680 });
    await page.getByRole('button', { name: '切换材料列表', exact: true }).click();
    await page.locator('.material-panel').waitFor();
    const fits = await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth);
    assert.ok(fits, '980px布局不应产生水平溢出');
    fs.writeFileSync(path.join(root, 'artifacts', 'workspace-compact.png'), await page.screenshot());
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(root, 'artifacts', 'workspace-desktop-result.json'), JSON.stringify({ topicNavigation: true, settingsPreserveBranchAndDraft: true, sourceManagement: true, memoryScopeIsolation: true, readDiscussSwitch: true, compactLayout: true, pageErrors: errors }, null, 2));
    console.log('Workspace navigation, settings, source management, memory isolation, draft and compact layout: passed.');
  } catch (error) {
    if (page) fs.writeFileSync(path.join(root, 'artifacts', 'workspace-desktop-failure.png'), await page.screenshot().catch(() => Buffer.alloc(0)));
    fs.writeFileSync(path.join(root, 'artifacts', 'workspace-desktop-failure.json'), JSON.stringify({ error: error.message }, null, 2));
    throw error;
  } finally { await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
